#!/usr/bin/env python3
"""Regenerate explicit kernel-checkable rational power interval proofs.

This generator is not trusted: every emitted multiplication and inequality
is checked by Lean. No native_decide or external oracle is used.
"""
from fractions import Fraction as F
from pathlib import Path

Q = 10**30
HEADER = '''import SharpOC.BoxParameters

/-! Explicit rational interval certificates for the two large powers.
Generated by scripts/generate_box_power_certificate.py; every bound below
is proved in Lean from rational arithmetic and monotone multiplication. -/

noncomputable section
namespace SharpOC.BoxParameters

private theorem power_product_interval {x : ℝ} {a b : ℕ} {la ua lb ub l u : ℝ}
    (ha : la ≤ x^a ∧ x^a ≤ ua) (hb : lb ≤ x^b ∧ x^b ≤ ub)
    (hla : 0 ≤ la) (hlb : 0 ≤ lb) (hl : l ≤ la*lb) (hu : ua*ub ≤ u) :
    l ≤ x^(a+b) ∧ x^(a+b) ≤ u := by
  rw [pow_add]
  exact ⟨hl.trans (mul_le_mul ha.1 hb.1 hlb (hla.trans ha.1)),
    (mul_le_mul ha.2 hb.2 (hlb.trans hb.1) ((hla.trans ha.1).trans ha.2)).trans hu⟩

'''
def rat(f):
    f=F(f)
    return f'({f.numerator}/{f.denominator} : ℝ)'

def make(name, base, exponent):
    lines=[]; bounds={1:(base.numerator*Q//base.denominator,(base.numerator*Q+base.denominator-1)//base.denominator)}
    def interval(n):
        l,u=bounds[n]
        return f'{rat(F(l,Q))} ≤ x^{n} ∧ x^{n} ≤ {rat(F(u,Q))}'
    lines.append(f'  have h1 : {interval(1)} := by norm_num [x]')
    def get(n):
        if n in bounds:return
        a=n//2;get(a)
        b=n-a;get(b)
        la,ua=bounds[a];lb,ub=bounds[b]
        l=la*lb//Q;u=(ua*ub+Q-1)//Q;bounds[n]=(l,u)
        lines.extend([f'  have h{n} : {interval(n)} := by',
          f'    have hh := power_product_interval (x := x) (a := {a}) (b := {b}) h{a} h{b}',
          '      (by norm_num) (by norm_num)',
          f'      (show {rat(F(l,Q))} ≤ {rat(F(la,Q))} * {rat(F(lb,Q))} by norm_num)',
          f'      (show {rat(F(ua,Q))} * {rat(F(ub,Q))} ≤ {rat(F(u,Q))} by norm_num)',
          '    simpa only [Nat.reduceAdd] using hh'])
    get(exponent)
    l,u=bounds[exponent]
    statement=f'theorem {name} :\n    {rat(F(l,Q))} ≤ {rat(base)}^{exponent} ∧\n      {rat(base)}^{exponent} ≤ {rat(F(u,Q))} := by\n  let x : ℝ := {rat(base)}\n'
    return statement+'\n'.join(lines)+f'\n  exact h{exponent}\n\n'
text=HEADER+make('growth_power_bounds',F(500001,500000),1372128)+make('decay_power_bounds',F(499999,500000),1372128)+'end SharpOC.BoxParameters\n'
root=Path(__file__).resolve().parents[1]
p=root/'lean/SharpOC/BoxPowerCertificates.lean'
p.write_text(text)
print(p.relative_to(root))
